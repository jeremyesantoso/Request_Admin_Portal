CREATE DATABASE IF NOT EXISTS BAKERY_DB;
USE BAKERY_DB;

CREATE TABLE IF NOT EXISTS ORDERS (
    ID INT AUTO_INCREMENT,
    CUSTOMER_NAME VARCHAR(100) NOT NULL,
    CUSTOMER_EMAIL VARCHAR(100) NOT NULL,
    CUSTOMER_MOBILE VARCHAR(50) NOT NULL,
    PICKUP_DATE DATE NOT NULL,
    PICKUP_TIME TIME NOT NULL,
    PAYMENT_METHOD ENUM('E-Transfer', 'Cash') DEFAULT 'E-Transfer',
    DEPOSIT_PAID BOOLEAN DEFAULT FALSE,
    TOTAL_PRICE DECIMAL(10, 2) DEFAULT 0.00,
    STATUS ENUM('New Inquiry', 'Quote Sent', 'Deposit Paid', 'In Progress', 'Completed', 'Cancelled') DEFAULT 'New Inquiry',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY(ID)
);

CREATE TABLE IF NOT EXISTS CAKE_SPECS (
    ID INT AUTO_INCREMENT,
    ORDER_ID INT NOT NULL,
    CAKE_SHAPE ENUM('Round', 'Heart', 'Custom') NOT NULL,
    CAKE_SIZE ENUM(
        'Bento (4")', 
        'Standard (6")', 
        'Large (8")', 
        'Big Celebration (4" + 6")', 
        'Big Celebration (6" + 8")'
    ) NOT NULL,
    CAKE_FLAVOUR ENUM(
        'Classic Vanilla', 
        'Chocolate Hazelnut', 
        'Strawberry Shortcake', 
        'Red Velvet'
    ) NOT NULL,
    CANDLE_OPTION ENUM('None', 'Standard (+$1)', 'Premium (+$3)') DEFAULT 'None',
    DIET_NOTES VARCHAR(255) DEFAULT 'None',
    DESIGN_MESSAGE_NOTES TEXT,

    PRIMARY KEY(ID),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS INSPO_PICS (
    ID INT AUTO_INCREMENT,
    ORDER_ID INT NOT NULL,
    PHOTO_URL VARCHAR(255) NOT NULL,
    UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY(ID),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE CASCADE
);